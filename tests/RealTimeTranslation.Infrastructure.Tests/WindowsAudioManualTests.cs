using System.Buffers.Binary;
using NAudio.Wave;
using RealTimeTranslation.Core;
using RealTimeTranslation.Infrastructure.Audio;

namespace RealTimeTranslation.Infrastructure.Tests;

public sealed class WindowsAudioManualTests
{
    [Trait("Category", "WindowsAudioManual")]
    [Fact]
    public async Task SystemLoopbackCapturesPlayback()
    {
        RequireManualRun();
        var tone = CreatePcm16StereoTone();
        using var stream = new RawSourceWaveStream(
            new MemoryStream(tone, writable: false),
            new WaveFormat(48_000, 16, 2));
        using var playback = new WaveOut();
        playback.Init(stream);
        await CaptureForFiveSeconds(new SystemLoopbackAudioSource(), playback.Play);
    }

    [Trait("Category", "WindowsAudioManual")]
    [Fact]
    public async Task MicrophoneCapturesInputSignal()
    {
        RequireManualRun();
        await CaptureForFiveSeconds(new MicrophoneAudioSource(), null);
    }

    private static void RequireManualRun()
    {
        if (Environment.GetEnvironmentVariable("RUN_WINDOWS_AUDIO_TESTS") != "1")
        {
            Assert.Skip("Set RUN_WINDOWS_AUDIO_TESTS=1. System playback is generated by the test; speak for the microphone check.");
        }
    }

    private static async Task CaptureForFiveSeconds(
        IAudioCaptureSource source,
        Action? afterStart)
    {
        await using (source)
        {
            var metricsSync = new object();
            var frames = 0;
            var bytes = 0;
            var nonZeroSamples = 0;
            var peakAmplitude = 0;
            var invalidFrames = 0;
            var faults = 0;
            source.FrameAvailable += (_, args) =>
            {
                var data = args.Frame.Data;
                var framePeak = 0;
                var frameNonZero = 0;
                for (var offset = 0; offset + 1 < data.Length; offset += 2)
                {
                    var sample = BinaryPrimitives.ReadInt16LittleEndian(data.AsSpan(offset, 2));
                    var amplitude = Math.Abs((int)sample);
                    framePeak = Math.Max(framePeak, amplitude);
                    if (sample != 0)
                    {
                        frameNonZero++;
                    }
                }

                lock (metricsSync)
                {
                    frames++;
                    bytes += data.Length;
                    nonZeroSamples += frameNonZero;
                    peakAmplitude = Math.Max(peakAmplitude, framePeak);
                    if (data.Length is 0 or > 3_200 || data.Length % 2 != 0)
                    {
                        invalidFrames++;
                    }
                }
            };
            source.Faulted += (_, _) => Interlocked.Increment(ref faults);

            Assert.Equal(AudioFormat.AzurePcm, source.OutputFormat);
            await source.StartAsync(TestContext.Current.CancellationToken);
            afterStart?.Invoke();
            await Task.Delay(TimeSpan.FromSeconds(5), TestContext.Current.CancellationToken);
            await source.StopAsync(CancellationToken.None);
            TestContext.Current.TestOutputHelper?.WriteLine(
                $"source={source.GetType().Name} frames={frames} bytes={bytes} "
                + $"nonzero-samples={nonZeroSamples} peak-amplitude={peakAmplitude} "
                + $"invalid-frames={invalidFrames} faults={faults}");
            Assert.True(frames > 0, "No PCM frames captured. Play audio for loopback or speak for microphone.");
            Assert.True(bytes > 0);
            Assert.Equal(0, invalidFrames);
            Assert.Equal(0, faults);
            Assert.True(nonZeroSamples > 0, "The device emitted PCM frames but no audible signal was captured.");
            Assert.True(peakAmplitude > 0);
        }
    }

    private static byte[] CreatePcm16StereoTone()
    {
        const int sampleRate = 48_000;
        const int seconds = 4;
        var bytes = new byte[sampleRate * seconds * 2 * sizeof(short)];
        for (var frame = 0; frame < sampleRate * seconds; frame++)
        {
            var sample = (short)(Math.Sin(2 * Math.PI * 440 * frame / sampleRate)
                * short.MaxValue * 0.05);
            var offset = frame * 2 * sizeof(short);
            BinaryPrimitives.WriteInt16LittleEndian(bytes.AsSpan(offset, 2), sample);
            BinaryPrimitives.WriteInt16LittleEndian(bytes.AsSpan(offset + 2, 2), sample);
        }

        return bytes;
    }
}
